def Euler2R(ang):
    """
    Converts an Euler angles vector [phi, theta, psi] into a rotation matrix
    of the Z-Y-X representation:
        R = rot_z(psi) * rot_y(theta) * rot_x(phi)

    Parameters:
        ang : array-like
            Euler angles [phi, theta, psi] in radians

    Returns:
        rot : numpy.ndarray
            3x3 rotation matrix
    """

    phi, theta, psi = ang

    rotx = np.array([
        [1, 0, 0],
        [0, np.cos(phi), -np.sin(phi)],
        [0, np.sin(phi),  np.cos(phi)]
    ])

    roty = np.array([
        [ np.cos(theta), 0, np.sin(theta)],
        [0,              1, 0],
        [-np.sin(theta), 0, np.cos(theta)]
    ])

    rotz = np.array([
        [np.cos(psi), -np.sin(psi), 0],
        [np.sin(psi),  np.cos(psi), 0],
        [0,            0,           1]
    ])

    rot = rotz @ roty @ rotx

    return rot

def linear_motion_ref(q, q_d, param: Param):
    """
    Linear motion reference update.

    Parameters
    ----------
    q : ndarray, shape (3,)
        Current reduced attitude vector.
    q_d : ndarray, shape (3,)
        Desired reduced attitude vector.
    param : object
        Object with attributes:
            - k_geometric : float
            - dTi : float

    Returns
    -------
    q : ndarray, shape (3,)
        Updated reduced attitude.
    e_q : ndarray, shape (3,)
        Configuration error.
    """
    # ---------- Configuration error ----------
    e_q = skew(q_d) @ q / np.sqrt(2 * (1 + np.dot(q.T, q_d)))

    # ---------- Reduced attitude kinematics ----------
    q_dot = -param.k_geometric * (skew(e_q) @ q)
    q = q + param.sim.dTi * q_dot
    q = q / np.linalg.norm(q)

    return q, e_q

